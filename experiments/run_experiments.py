"""
experiments/run_experiments.py

Runs the (mildly expensive, O(N^2)-ish for large sweeps) experiments once and
writes the results to precomputed/precomputed_results.json, exactly as the
official rules recommend ("Precompute expensive results and ship them as
data"). The live web artifact reloads this file for the reference curves and
also performs its own small, fast, LIVE recomputation of the same formulas in
JS for whatever the learner sets the sliders to (see web/index.html).

Every number in the JSON below was produced by core/linear_memory.py -- none
of it is invented, and none of it is a benchmark or claim about BDH itself.
It measures the behavior of our own toy Hebbian associative memory.
"""

import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from core.linear_memory import run_associative_memory  # noqa: E402

OUT_PATH = os.path.join(
    os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
    "precomputed",
    "precomputed_results.json",
)


def sweep_load_factor(n=128, num_classes=32, sparsity=0.05, seed=42, trials=5):
    loads = [0.1, 0.25, 0.5, 0.75, 1.0, 1.25, 1.5, 2.0, 2.5, 3.0, 4.0, 5.0, 6.0, 8.0]
    out = []
    for load in loads:
        N = max(1, int(round(load * n)))
        accs = [
            run_associative_memory(
                n=n, num_classes=num_classes, num_written=N,
                sparsity=sparsity, seed=seed + t,
            ).accuracy
            for t in range(trials)
        ]
        out.append({
            "load_factor": load,
            "num_written": N,
            "accuracy_mean": sum(accs) / len(accs),
            "accuracy_min": min(accs),
            "accuracy_max": max(accs),
        })
    return out


def sweep_sparsity(n=128, num_classes=32, num_written=256, seed=7, trials=5):
    sparsities = [0.01, 0.02, 0.05, 0.1, 0.15, 0.2, 0.3, 0.4, 0.6, 0.8, 1.0]
    out = []
    for s in sparsities:
        accs = [
            run_associative_memory(
                n=n, num_classes=num_classes, num_written=num_written,
                sparsity=s, seed=seed + t,
            ).accuracy
            for t in range(trials)
        ]
        out.append({
            "sparsity": s,
            "accuracy_mean": sum(accs) / len(accs),
            "accuracy_min": min(accs),
            "accuracy_max": max(accs),
        })
    return out


def sweep_noise(n=128, num_classes=32, num_written=96, sparsity=0.05, seed=11, trials=5):
    noises = [0.0, 0.02, 0.05, 0.1, 0.15, 0.2, 0.3, 0.5, 0.8, 1.2]
    out = []
    for nz in noises:
        accs = [
            run_associative_memory(
                n=n, num_classes=num_classes, num_written=num_written,
                sparsity=sparsity, noise=nz, seed=seed + t,
            ).accuracy
            for t in range(trials)
        ]
        out.append({
            "noise": nz,
            "accuracy_mean": sum(accs) / len(accs),
            "accuracy_min": min(accs),
            "accuracy_max": max(accs),
        })
    return out


def kv_cache_growth(max_n=2000, step=100, key_bytes_per_token=32):
    out = []
    for N in range(step, max_n + 1, step):
        out.append({
            "num_written": N,
            "accuracy": 1.0,
            "bytes": N * key_bytes_per_token,
        })
    return out


def fixed_state_bytes(n=128, num_classes=32):
    import numpy as np
    return int(n * num_classes * np.zeros((1,)).itemsize * 8)  # float64 nominal


def main():
    results = {
        "label": "PRECOMPUTED — generated by experiments/run_experiments.py from core/linear_memory.py. "
                  "Real numpy computation, not illustrative.",
        "fixed_params": {"n": 128, "num_classes": 32, "sparsity_default": 0.05},
        "load_factor_sweep": sweep_load_factor(),
        "sparsity_sweep": sweep_sparsity(),
        "noise_sweep": sweep_noise(),
        "kv_cache_growth": kv_cache_growth(),
        "fixed_state_bytes_at_default": fixed_state_bytes(),
    }
    os.makedirs(os.path.dirname(OUT_PATH), exist_ok=True)
    with open(OUT_PATH, "w") as f:
        json.dump(results, f, indent=2)
    print(f"Wrote {OUT_PATH}")
    print(f"load_factor_sweep points: {len(results['load_factor_sweep'])}")
    print(f"sparsity_sweep points: {len(results['sparsity_sweep'])}")
    print(f"noise_sweep points: {len(results['noise_sweep'])}")


if __name__ == "__main__":
    main()
